"""Pydantic schemas for the ShopAI backend."""

from typing import List, Optional
from pydantic import BaseModel, Field


class AttributeValue(BaseModel):
    """Structured representation of an extracted visual attribute."""
    value: str = Field(..., description="Detected value or 'Not confidently detected'")
    confidence: str = Field(..., description="Confidence level: high, medium, low, uncertain")
    source: str = Field(..., description="Method used: image analysis, caption heuristic, user hint, etc.")


class VisualAttributes(BaseModel):
    """The 5 key visual attributes required for Shopify product creation."""
    category: AttributeValue
    main_color: AttributeValue
    shape_style: AttributeValue
    pattern: AttributeValue
    visible_texture: AttributeValue


class ProductDescriptionResponse(BaseModel):
    """Complete structured response contract for product generation."""
    caption: str = Field(..., description="Raw caption generated by Salesforce BLIP")
    product_title: str = Field(..., description="AI-generated or proposed product title")
    visual_attributes: VisualAttributes = Field(..., description="Extracted visual attributes")
    full_description: str = Field(..., description="Shopify-ready marketing description grounded in visible traits")
    key_features: List[str] = Field(..., description="Editable bullet points of visible features")
    uncertainty_notes: List[str] = Field(
        default_factory=list,
        description="Notices highlighting estimates that should be verified by the shopkeeper"
    )


class HealthResponse(BaseModel):
    """Response returned by GET /api/health."""
    status: str = Field(..., json_schema_extra={"example": "ok"})
    model_loaded: bool = Field(..., description="Whether BLIP weights are loaded into memory")
    device: str = Field(..., json_schema_extra={"example": "cpu"})
    model_name: str = Field(..., json_schema_extra={"example": "Salesforce/blip-image-captioning-base"})
    version: str = Field(..., json_schema_extra={"example": "1.0.0"})


class ErrorResponse(BaseModel):
    """Standard error response model."""
    error: str
    detail: Optional[str] = None
